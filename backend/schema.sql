-- ---------- 1. TABEL ----------

create table if not exists public.produk (
  id          bigint generated by default as identity primary key,
  nama        text    not null,
  kategori    text    not null default 'Lainnya',
  harga       numeric(12,0) not null default 0 check (harga >= 0),
  stok        integer not null default 0 check (stok >= 0),
  min_stok    integer not null default 5 check (min_stok >= 0),
  emoji       text    not null default '🍪',
  created_at  timestamptz not null default now()
);

create table if not exists public.pelanggan (
  id          bigint generated by default as identity primary key,
  nama        text not null,
  hp          text,
  email       text,
  alamat      text,
  created_at  timestamptz not null default now()
);

create table if not exists public.penjualan (
  id            bigint generated by default as identity primary key,
  tanggal       date    not null default current_date,
  pelanggan_id  bigint  references public.pelanggan(id) on delete set null,
  produk_id     bigint  references public.produk(id)    on delete set null,
  qty           integer not null check (qty > 0),
  harga         numeric(12,0) not null default 0 check (harga >= 0),  -- snapshot harga saat transaksi
  total         numeric(14,0) generated always as (qty * harga) stored,
  metode        text    not null default 'Cash'
                check (metode in ('Cash','QRIS','Transfer','Debit')),
  catatan       text    default '',
  created_at    timestamptz not null default now()
);

create table if not exists public.pengeluaran (
  id          bigint generated by default as identity primary key,
  tanggal     date not null default current_date,
  keterangan  text not null,
  kategori    text not null default 'Lainnya'
              check (kategori in ('Bahan baku','Kemasan','Operasional','Transportasi','Gaji','Lainnya')),
  nominal     numeric(14,0) not null check (nominal > 0),
  metode      text not null default 'Cash'
              check (metode in ('Cash','QRIS','Transfer','Debit')),
  created_at  timestamptz not null default now()
);

create index if not exists idx_penjualan_tanggal   on public.penjualan(tanggal);
create index if not exists idx_penjualan_pelanggan on public.penjualan(pelanggan_id);
create index if not exists idx_penjualan_produk    on public.penjualan(produk_id);
create index if not exists idx_pengeluaran_tanggal on public.pengeluaran(tanggal);

-- ---------- 2. TRIGGER STOK OTOMATIS ----------
-- Insert penjualan  -> stok produk berkurang (ditolak jika stok kurang)
-- Hapus penjualan   -> stok dikembalikan
-- Update penjualan  -> stok lama dikembalikan, stok baru dikurangi

create or replace function public.fn_penjualan_before_insert()
returns trigger language plpgsql as $$
declare
  v_stok  integer;
  v_harga numeric;
  v_nama  text;
begin
  select stok, harga, nama into v_stok, v_harga, v_nama
  from public.produk where id = new.produk_id for update;

  if not found then
    raise exception 'Produk tidak ditemukan';
  end if;

  if v_stok < new.qty then
    raise exception 'Stok % tidak cukup. Tersedia % pcs.', v_nama, v_stok;
  end if;

  -- jika harga tidak dikirim (0), pakai harga katalog sebagai snapshot
  if coalesce(new.harga, 0) = 0 then
    new.harga := v_harga;
  end if;

  update public.produk set stok = stok - new.qty where id = new.produk_id;
  return new;
end $$;

create or replace function public.fn_penjualan_before_update()
returns trigger language plpgsql as $$
declare
  v_stok integer;
  v_nama text;
begin
  if old.produk_id is not null then
    update public.produk set stok = stok + old.qty where id = old.produk_id;
  end if;

  select stok, nama into v_stok, v_nama
  from public.produk where id = new.produk_id for update;

  if not found then
    raise exception 'Produk tidak ditemukan';
  end if;
  if v_stok < new.qty then
    raise exception 'Stok % tidak cukup. Tersedia % pcs.', v_nama, v_stok;
  end if;

  update public.produk set stok = stok - new.qty where id = new.produk_id;
  return new;
end $$;

create or replace function public.fn_penjualan_after_delete()
returns trigger language plpgsql as $$
begin
  if old.produk_id is not null then
    update public.produk set stok = stok + old.qty where id = old.produk_id;
  end if;
  return old;
end $$;

drop trigger if exists trg_penjualan_bi on public.penjualan;
drop trigger if exists trg_penjualan_bu on public.penjualan;
drop trigger if exists trg_penjualan_ad on public.penjualan;

create trigger trg_penjualan_bi before insert on public.penjualan
  for each row execute function public.fn_penjualan_before_insert();
create trigger trg_penjualan_bu before update on public.penjualan
  for each row execute function public.fn_penjualan_before_update();
create trigger trg_penjualan_ad after delete on public.penjualan
  for each row execute function public.fn_penjualan_after_delete();

-- ---------- 3. VIEW LAPORAN ----------

create or replace view public.v_penjualan_detail
with (security_invoker = true) as
select s.id, s.tanggal, s.qty, s.harga, s.total, s.metode, s.catatan,
       s.pelanggan_id, c.nama as pelanggan,
       s.produk_id,    p.nama as produk
from public.penjualan s
left join public.pelanggan c on c.id = s.pelanggan_id
left join public.produk    p on p.id = s.produk_id;

create or replace view public.v_ringkasan
with (security_invoker = true) as
select
  (select coalesce(sum(total),0)   from public.penjualan)   as total_penjualan,
  (select coalesce(sum(nominal),0) from public.pengeluaran) as total_pengeluaran,
  (select coalesce(sum(total),0)   from public.penjualan)
  - (select coalesce(sum(nominal),0) from public.pengeluaran) as laba_bersih,
  (select coalesce(sum(stok * harga),0) from public.produk) as nilai_stok,
  (select coalesce(sum(stok),0)         from public.produk) as total_stok_pcs;

-- ---------- 4. ROW LEVEL SECURITY ----------
-- Aplikasi memakai publishable (anon) key TANPA login, jadi policy di bawah
-- membuka akses penuh untuk role anon. Siapa pun yang punya key + URL bisa
-- membaca/mengubah data. Untuk produksi, aktifkan Supabase Auth dan ganti
-- "to anon, authenticated" menjadi "to authenticated".

alter table public.produk      enable row level security;
alter table public.pelanggan   enable row level security;
alter table public.penjualan   enable row level security;
alter table public.pengeluaran enable row level security;

do $$
declare t text;
begin
  foreach t in array array['produk','pelanggan','penjualan','pengeluaran'] loop
    execute format('drop policy if exists "akses_penuh_%1$s" on public.%1$I', t);
    execute format(
      'create policy "akses_penuh_%1$s" on public.%1$I for all to anon, authenticated using (true) with check (true)', t);
  end loop;
end $$;

